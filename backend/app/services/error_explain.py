# Последняя непустая строка traceback'а Python: "ИмяОшибки: сообщение".
_LAST_LINE_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*(?:Error|Exception|Warning)):?\s*(.*)$")
_QUOTED_NAME_RE = re.compile(r"'([^']+)'")


def explain_stderr_ru(stderr: str | None) -> str | None:
    """Ищет тип исключения в последней строке stderr и возвращает краткое
    объяснение на русском, либо None (не traceback / тип не распознан)."""
    if not stderr:
        return None
    lines = [line for line in stderr.strip().splitlines() if line.strip()]
    if not lines:
        return None
    match = _LAST_LINE_RE.match(lines[-1].strip())
    if not match:
        return None
    exc_type, message = match.group(1), match.group(2)
    explanation = _EXPLANATIONS.get(exc_type)
    if not explanation:
        return None
    if exc_type in ("NameError", "AttributeError", "ModuleNotFoundError", "UnboundLocalError"):
        name_match = _QUOTED_NAME_RE.search(message)
        if name_match:
            return f"{explanation} Похоже, речь про «{name_match.group(1)}»."
    return explanation


